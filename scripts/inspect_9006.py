import sys
import os

env_file = "/etc/trikonekt/staging-backend.env"
if os.path.exists(env_file):
    with open(env_file, "r") as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                os.environ.setdefault(k.strip(), v.strip())

staging_backend_dir = os.environ.get("GROWTH_BACKEND_DIR", "/srv/trikonekt/staging/backend")
if os.path.exists(staging_backend_dir):
    sys.path.insert(0, staging_backend_dir)

os.environ.setdefault("DJANGO_SETTINGS_MODULE", "core.settings")

import django
django.setup()

from accounts.models import CustomUser, WalletTransaction
from mlm_ranks.models import RankUpgrade, UpgradeCommission, RankMatrixNode

u = CustomUser.objects.filter(phone='9000000006').first()
print(f"User 9000000006: {u}")
if u:
    print(f"Sponsor: {getattr(u, 'sponsor', None)}")
    upgrades = RankUpgrade.objects.filter(user=u).order_by('id')
    for up in upgrades:
        lvl = up.to_rank.level_number if up.to_rank else None
        print(f"Upgrade To Rank {lvl}: status={up.payment_status}, amount={up.upgrade_amount}, created={up.created_at}")

nodes = RankMatrixNode.objects.filter(placed_user=u)
print(f"\n--- Matrix Nodes for 9000000006 ---")
for n in nodes:
    parent_phone = n.parent_user.phone if n.parent_user else "None"
    print(f"Node id={n.id}, level_depth={n.level_depth}, parent={parent_phone}, position={n.position}")

commissions = UpgradeCommission.objects.filter(upgrade__user=u).order_by('id')
print(f"\n--- Upgrade Commissions generated by 9000000006 (Total: {commissions.count()}) ---")
for c in commissions:
    ben_phone = c.beneficiary.phone if c.beneficiary else "None/Overhead"
    print(f"Beneficiary: {ben_phone} | Amount: {c.amount} | Level: {getattr(c, 'level_index', getattr(c, 'distance', getattr(c, 'matrix_level', 'unknown')))} | Status: {c.status}")

txs = WalletTransaction.objects.filter(meta__contains='9000000006').order_by('id')
print(f"\n--- TXs involving 9000000006 in meta (Total: {txs.count()}) ---")
for t in txs:
    print(f"User: {t.wallet.user.phone} | Type: {t.transaction_type} | Amount: {t.amount} | Desc: {t.description}")
